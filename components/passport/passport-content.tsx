"use client"

import { useEffect, useMemo, useState } from "react"
import { motion } from "framer-motion"
import useSWR from "swr"
import {
  FileText,
  Leaf,
  Award,
  Download,
  CheckCircle,
  Clock,
  Building2,
  Calendar,
  Hash,
  Printer,
  X,
  ShieldCheck,
  AlertTriangle,
} from "lucide-react"
import { toast } from "sonner"
import Link from "next/link"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { Badge } from "@/components/ui/badge"
import { Progress } from "@/components/ui/progress"
import { ResponsiveContainer, RadarChart, PolarGrid, PolarAngleAxis, PolarRadiusAxis, Radar, Tooltip } from "recharts"
import { usePortfolio } from "@/hooks/use-portfolio"
import { useSandbox } from "@/lib/demo/sandbox"
import { tooltipStyle } from "@/components/dashboard/market-charts"

const fetcher = (url: string) => fetch(url).then((res) => res.json())

interface PassportApi {
  passport: null | {
    id: string
    companyName: string
    industrySector: string
    verifiedEmissions: number
    pendingEmissions: number
    creditsOwned: number
    emissionReductionTarget: number
    complianceStatus: "compliant" | "non-compliant" | "pending"
    trustScore: number
    sustainabilityRating: string
    lastAuditDate: string
    createdAt: string
    tradeCount: number
    reportingMonths: number
  }
}

const DISCLAIMER =
  "This document is generated by the CarbonEx platform and is a temporary carbon passport only. It is not an official certificate and cannot be used as a legal certification until it is verified by the relevant authority."

const CERTIFICATIONS = [
  { name: "ISO 14064-1", status: "Active", expires: "2028-12-31" },
  { name: "GHG Protocol Corporate Standard", status: "Active", expires: "2028-06-30" },
  { name: "Science Based Targets initiative", status: "Verification in progress", expires: "" },
]

async function sha256(text: string) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text))
  return Array.from(new Uint8Array(digest)).map((b) => b.toString(16).padStart(2, "0")).join("")
}

const containerVariants = { hidden: { opacity: 0 }, visible: { opacity: 1, transition: { staggerChildren: 0.1 } } }
const itemVariants = { hidden: { opacity: 0, y: 20 }, visible: { opacity: 1, y: 0 } }

export function PassportContent() {
  const { data, isLoading, mutate } = useSWR<PassportApi>("/api/passport", fetcher)
  const { portfolio } = usePortfolio()
  const sandbox = useSandbox()
  const [printMode, setPrintMode] = useState<"none" | "bee" | "audit">("none")
  const [generating, setGenerating] = useState(false)
  const [recordHash, setRecordHash] = useState("")

  const raw = data?.passport
  const passport = useMemo(() => {
    if (!raw) return null
    const sandboxPending = sandbox.emissions.reduce((sum, e) => sum + e.amount, 0)
    const creditsOwned = portfolio?.holdings ?? raw.creditsOwned
    const shortfall = raw.verifiedEmissions - creditsOwned
    const coverage = raw.verifiedEmissions > 0 ? Math.min(100, (creditsOwned / raw.verifiedEmissions) * 100) : 0
    return {
      ...raw,
      creditsOwned,
      pendingEmissions: raw.pendingEmissions + sandboxPending,
      shortfall,
      coverage,
      tradeCount: raw.tradeCount + sandbox.trades.length,
    }
  }, [raw, portfolio?.holdings, sandbox.emissions, sandbox.trades.length])

  useEffect(() => {
    if (!passport) return
    const record = JSON.stringify({
      id: passport.id,
      company: passport.companyName,
      verified: passport.verifiedEmissions,
      credits: passport.creditsOwned,
      status: passport.complianceStatus,
      issued: passport.createdAt,
    })
    sha256(record).then(setRecordHash).catch(() => setRecordHash(""))
  }, [passport])

  const metrics = useMemo(() => {
    if (!passport) return []
    return [
      { metric: "Offset coverage", value: Math.round(passport.coverage) },
      { metric: "Compliance", value: passport.complianceStatus === "compliant" ? 92 : passport.complianceStatus === "pending" ? 60 : 30 },
      { metric: "Trust score", value: passport.trustScore },
      { metric: "Trading", value: Math.min(100, 40 + passport.tradeCount * 4) },
      { metric: "Reporting", value: Math.round(Math.min(12, passport.reportingMonths) / 12 * 100) },
      { metric: "Reduction target", value: Math.min(100, passport.emissionReductionTarget * 2) },
    ]
  }, [passport])

  async function generatePassport() {
    setGenerating(true)
    try {
      const res = await fetch("/api/passport", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" })
      const result = await res.json()
      if (!res.ok) {
        toast.error(result.error || "Could not generate the passport")
        return
      }
      toast.success(result.message)
      await mutate(result.simulated ? { passport: result.passport } : undefined, { revalidate: !result.simulated })
    } catch {
      toast.error("Could not generate the passport")
    } finally {
      setGenerating(false)
    }
  }

  if (isLoading) {
    return (
      <div className="flex h-[60vh] items-center justify-center">
        <div className="text-muted-foreground">Loading passport data...</div>
      </div>
    )
  }

  if (!passport) {
    return (
      <div className="flex h-[60vh] flex-col items-center justify-center gap-4 text-center">
        <FileText className="h-16 w-16 text-muted-foreground" />
        <h2 className="text-2xl font-semibold">No carbon passport yet</h2>
        <p className="max-w-md text-muted-foreground">Generate a passport to start tracking verified emissions, credits and certifications for your organization.</p>
        <Button className="mt-2 bg-emerald-600 text-white hover:bg-emerald-700" onClick={generatePassport} disabled={generating}>
          {generating ? "Generating..." : "Generate passport"}
        </Button>
      </div>
    )
  }

  const issued = new Date(passport.createdAt).toLocaleDateString()
  const positionLabel = passport.shortfall > 0 ? "Offset shortfall" : "Offset surplus"

  if (printMode !== "none") {
    return (
      <div className="carbon-document-preview no-print-bg fixed inset-0 z-50 min-h-dvh overflow-y-auto bg-zinc-100 text-zinc-900">
        <div className="no-print sticky top-0 z-50 flex flex-wrap items-center justify-between gap-3 border-b border-zinc-200 bg-white px-4 py-3 shadow-sm">
          <div className="flex flex-wrap items-center gap-3">
            <h2 className="text-lg font-semibold text-zinc-900">Document preview</h2>
            <Badge variant="outline" className="border-blue-200 bg-blue-50 text-blue-700">
              {printMode === "bee" ? "BEE reporting format" : "Internal audit record"}
            </Badge>
          </div>
          <div className="flex items-center gap-3">
            <Button variant="outline" className="border-zinc-300 bg-white text-zinc-900 hover:bg-zinc-50" onClick={() => setPrintMode("none")}>
              <X className="mr-2 h-4 w-4" /> Close
            </Button>
            <Button onClick={() => window.print()} className="bg-emerald-600 text-white hover:bg-emerald-700">
              <Printer className="mr-2 h-4 w-4" /> Print or save as PDF
            </Button>
          </div>
        </div>

        <div className="print-canvas flex justify-center px-3 py-5 sm:py-12">
          <div className="print-document relative w-full min-w-0 max-w-[800px] overflow-hidden border border-zinc-300 bg-white p-4 font-serif text-zinc-900 shadow-xl sm:p-8 lg:p-12">
            <div aria-hidden className="pointer-events-none absolute inset-0 flex items-center justify-center">
              <span className="rotate-[-30deg] select-none text-[7rem] font-bold tracking-widest text-zinc-900/[0.05]">SPECIMEN</span>
            </div>

            <div className="relative flex min-h-[900px] flex-col border-4 border-zinc-800 p-4 sm:p-8 lg:p-12">
              <div className="mb-6 border border-amber-600/50 bg-amber-50 px-3 py-2 text-center font-sans text-[11px] font-semibold uppercase tracking-wider text-amber-800">
                Specimen generated by CarbonEx · Not issued by any government authority
              </div>

              <div className="mb-10 shrink-0 border-b-2 border-zinc-800 pb-8 text-center">
                <h1 className="mb-3 text-2xl font-bold uppercase tracking-wider sm:text-3xl">
                  {printMode === "bee" ? "Carbon Emission and Compliance Summary" : "Internal Compliance Audit Record"}
                </h1>
                <p className="text-sm tracking-wide text-zinc-700 sm:text-base">
                  {printMode === "bee"
                    ? "Prepared in the reporting format of the Bureau of Energy Efficiency (BEE), Ministry of Power, Government of India"
                    : "CarbonEx Digital Carbon Passport · audit worksheet"}
                </p>
              </div>

              <div className="mb-8 grid shrink-0 grid-cols-1 gap-5 sm:grid-cols-2 sm:gap-8">
                <div>
                  <p className="text-sm font-bold uppercase text-zinc-500">Organization name</p>
                  <p className="text-2xl font-bold">{passport.companyName}</p>
                  <p className="mt-1 text-sm">Sector: {passport.industrySector}</p>
                </div>
                <div className="text-left sm:text-right">
                  <p className="text-sm font-bold uppercase text-zinc-500">Passport ID</p>
                  <p className="font-mono text-lg">{passport.id}</p>
                  <p className="mt-1 text-sm">Issued: {issued}</p>
                </div>
              </div>

              <div className="mb-12 grid shrink-0 grid-cols-1 gap-4 border border-zinc-300 bg-zinc-50 p-6 sm:grid-cols-3 sm:gap-6">
                <div>
                  <p className="mb-1 text-sm font-bold uppercase text-zinc-600">Verified emissions (12 months)</p>
                  <p className="text-2xl font-bold text-red-700">{passport.verifiedEmissions.toLocaleString()} tCO2e</p>
                </div>
                <div>
                  <p className="mb-1 text-sm font-bold uppercase text-zinc-600">Carbon credits held</p>
                  <p className="text-2xl font-bold text-green-700">{passport.creditsOwned.toLocaleString()} credits</p>
                </div>
                <div>
                  <p className="mb-1 text-sm font-bold uppercase text-zinc-600">{positionLabel}</p>
                  <p className="text-2xl font-bold">{Math.abs(passport.shortfall).toLocaleString()} tCO2e</p>
                </div>
              </div>

              <div className="mb-12 flex-1">
                {printMode === "bee" ? (
                  <div className="space-y-6">
                    <h3 className="border-b border-zinc-300 pb-2 text-xl font-bold">Certifications on record</h3>
                    <div className="space-y-3 text-sm font-semibold text-zinc-800">
                      {CERTIFICATIONS.map((c) => (
                        <p key={c.name}>{c.status === "Active" ? "✓" : "•"} {c.name}: {c.status}{c.expires ? `, valid until ${c.expires}` : ""}</p>
                      ))}
                    </div>
                    <p className="text-sm text-zinc-700">
                      Compliance status: <strong className="capitalize">{passport.complianceStatus}</strong> · Trust score {passport.trustScore}/100 · Last audit {passport.lastAuditDate}
                    </p>
                  </div>
                ) : (
                  <div className="space-y-6">
                    <h3 className="border-b border-zinc-300 pb-2 text-xl font-bold">Auditor sign off</h3>
                    <table className="w-full border-collapse border border-zinc-400 text-left text-sm">
                      <thead>
                        <tr className="bg-zinc-100">
                          <th className="w-1/4 border border-zinc-400 p-3">Auditor name</th>
                          <th className="w-1/4 border border-zinc-400 p-3">Role / department</th>
                          <th className="w-1/4 border border-zinc-400 p-3">Audit date</th>
                          <th className="w-1/4 border border-zinc-400 p-3">Remarks and signature</th>
                        </tr>
                      </thead>
                      <tbody>
                        {[0, 1, 2, 3].map((i) => (
                          <tr key={i} className="h-16">
                            <td className="border border-zinc-400 p-3" />
                            <td className="border border-zinc-400 p-3" />
                            <td className="border border-zinc-400 p-3" />
                            <td className="border border-zinc-400 p-3" />
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}
              </div>

              <div className="relative mt-8 flex shrink-0 flex-col items-end">
                <div className="mb-8 mr-4 rotate-[-8deg] sm:mr-12">
                  <div className="flex h-36 w-36 items-center justify-center rounded-full border-4 border-emerald-800 bg-white p-1">
                    <div className="flex h-full w-full flex-col items-center justify-center rounded-full border-2 border-emerald-800 px-2 text-center text-emerald-800">
                      <ShieldCheck className="mb-1 h-6 w-6" />
                      <span className="text-[10px] font-bold uppercase tracking-widest">CarbonEx</span>
                      <span className="text-[9px] font-bold uppercase">Platform record</span>
                      <span className="mt-1 font-mono text-[8px]">{recordHash.slice(0, 12)}</span>
                    </div>
                  </div>
                </div>

                <div className="w-full border-t border-zinc-400 pt-4 text-center">
                  <p className="mb-2 break-all font-mono text-[10px] text-zinc-500">Record SHA 256: {recordHash}</p>
                  <p className="font-sans text-xs italic text-zinc-600">
                    <strong>Disclaimer:</strong> {DISCLAIMER}
                  </p>
                </div>
              </div>
            </div>
          </div>
        </div>

        <style dangerouslySetInnerHTML={{ __html: `
          @media print {
            body { background: white !important; }
            .no-print, .no-print * { display: none !important; }
            .no-print-bg { background: white !important; position: static !important; }
            .print-canvas { padding: 0 !important; }
            .print-document { box-shadow: none !important; border: none !important; width: 100% !important; margin: 0 !important; padding: 0 !important; }
          }
        ` }} />
      </div>
    )
  }

  return (
    <motion.div className="no-print space-y-6" variants={containerVariants} initial="hidden" animate="visible">
      <motion.div variants={itemVariants} className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <p className="text-sm text-muted-foreground">Your platform record of verified emissions, credits held and certifications.</p>
        <div className="flex flex-wrap gap-2">
          <Button variant="outline" className="gap-2" onClick={() => setPrintMode("audit")}>
            <Printer className="h-4 w-4" /> Audit record
          </Button>
          <Button className="gap-2 bg-emerald-600 text-white hover:bg-emerald-700" onClick={() => setPrintMode("bee")}>
            <Download className="h-4 w-4" /> BEE format summary
          </Button>
        </div>
      </motion.div>

      <motion.div variants={itemVariants}>
        <Card className="overflow-hidden border-emerald-500/20 bg-gradient-to-br from-emerald-500/[0.06] to-card shadow-sm dark:from-emerald-950/30">
          <CardContent className="p-0">
            <div className="grid md:grid-cols-3">
              <div className="flex flex-col justify-center border-b border-border/60 p-6 sm:p-8 md:border-b-0 md:border-r">
                <div className="mb-6 flex items-center gap-4">
                  <div className="flex h-16 w-16 shrink-0 items-center justify-center rounded-full bg-emerald-500/15">
                    <Leaf className="h-8 w-8 text-emerald-600 dark:text-emerald-400" />
                  </div>
                  <div className="min-w-0">
                    <h3 className="text-xl font-bold text-foreground">{passport.companyName}</h3>
                    <p className="text-sm font-medium capitalize text-emerald-700 dark:text-emerald-400">Rating {passport.sustainabilityRating} · {passport.complianceStatus}</p>
                  </div>
                </div>
                <div className="mt-auto space-y-4">
                  <div className="flex items-center gap-3 text-sm"><Hash className="h-4 w-4 text-muted-foreground" /><span className="w-20 text-muted-foreground">ID</span><span className="font-mono font-medium text-foreground">{passport.id}</span></div>
                  <div className="flex items-center gap-3 text-sm"><Building2 className="h-4 w-4 text-muted-foreground" /><span className="w-20 text-muted-foreground">Sector</span><span className="font-medium">{passport.industrySector}</span></div>
                  <div className="flex items-center gap-3 text-sm"><Calendar className="h-4 w-4 text-muted-foreground" /><span className="w-20 text-muted-foreground">Last audit</span><span className="font-medium">{passport.lastAuditDate}</span></div>
                </div>
              </div>

              <div className="border-b border-border/60 bg-muted/40 p-6 sm:p-8 md:border-b-0 md:border-r">
                <h4 className="mb-6 text-sm font-bold uppercase tracking-wider text-muted-foreground">Emission metrics</h4>
                <div className="space-y-6">
                  <div>
                    <div className="mb-2 flex items-center justify-between gap-2 text-sm">
                      <span className="text-muted-foreground">Verified emissions, 12 months</span>
                      <span className="text-lg font-bold">{passport.verifiedEmissions.toLocaleString()} t</span>
                    </div>
                    <p className="text-xs text-muted-foreground">{passport.pendingEmissions.toLocaleString()} t pending verification</p>
                  </div>
                  <div>
                    <div className="mb-2 flex items-center justify-between gap-2 text-sm">
                      <span className="text-muted-foreground">Carbon credits held</span>
                      <span className="text-lg font-bold text-emerald-700 dark:text-emerald-400">{passport.creditsOwned.toLocaleString()}</span>
                    </div>
                    <Progress value={passport.coverage} className="h-2" aria-label="Offset coverage" />
                    <p className="mt-1 text-xs text-muted-foreground">Covers {passport.coverage.toFixed(1)}% of verified emissions</p>
                  </div>
                  <div className="border-t border-border/60 pt-4">
                    <div className="flex items-center justify-between gap-2 text-sm">
                      <span className="font-medium">{positionLabel}</span>
                      <span className={`text-xl font-bold ${passport.shortfall > 0 ? "text-amber-600 dark:text-amber-400" : "text-emerald-700 dark:text-emerald-400"}`}>
                        {Math.abs(passport.shortfall).toLocaleString()} tCO2e
                      </span>
                    </div>
                  </div>
                </div>
              </div>

              <div className="flex flex-col items-center justify-center p-6 text-center sm:p-8">
                <Badge className="mb-4 border-emerald-500/30 bg-emerald-500/15 px-4 py-1 text-sm text-emerald-700 dark:text-emerald-400">
                  <ShieldCheck className="mr-2 h-4 w-4" /> Platform record
                </Badge>
                <p className="mb-2 text-xs font-medium uppercase tracking-wider text-muted-foreground">Record SHA 256</p>
                <p className="mb-6 max-w-[220px] break-all font-mono text-xs text-foreground">{recordHash || "computing..."}</p>
                <div className="flex items-start gap-2 rounded-lg border border-amber-500/30 bg-amber-500/10 p-3 text-left">
                  <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-amber-600 dark:text-amber-400" />
                  <p className="text-xs text-muted-foreground">{DISCLAIMER}</p>
                </div>
              </div>
            </div>
          </CardContent>
        </Card>
      </motion.div>

      <div className="grid gap-6 md:grid-cols-2">
        <Card>
          <CardHeader>
            <CardTitle className="flex items-center gap-2"><Award className="h-5 w-5 text-emerald-600 dark:text-emerald-400" />Sustainability score</CardTitle>
            <CardDescription>Computed from your emissions, credits, trades and reports</CardDescription>
          </CardHeader>
          <CardContent>
            <ResponsiveContainer width="100%" height={300}>
              <RadarChart data={metrics}>
                <PolarGrid stroke="var(--color-border)" />
                <PolarAngleAxis dataKey="metric" tick={{ fill: "var(--color-muted-foreground)", fontSize: 11 }} />
                <PolarRadiusAxis angle={30} domain={[0, 100]} tick={{ fill: "var(--color-muted-foreground)", fontSize: 10 }} axisLine={false} />
                <Tooltip contentStyle={tooltipStyle} />
                <Radar name="Score" dataKey="value" stroke="var(--color-primary)" fill="var(--color-primary)" fillOpacity={0.4} />
              </RadarChart>
            </ResponsiveContainer>
          </CardContent>
        </Card>

        <Card className="flex flex-col">
          <CardHeader>
            <CardTitle className="flex items-center gap-2"><FileText className="h-5 w-5 text-emerald-600 dark:text-emerald-400" />Certifications</CardTitle>
            <CardDescription>Standards tracked on this passport</CardDescription>
          </CardHeader>
          <CardContent className="flex flex-1 flex-col gap-4">
            {CERTIFICATIONS.map((cert) => (
              <div key={cert.name} className="flex items-center gap-4 rounded-lg border border-border/60 bg-muted/40 p-4">
                <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full bg-emerald-500/15">
                  {cert.status === "Active" ? <Award className="h-5 w-5 text-emerald-600 dark:text-emerald-400" /> : <Clock className="h-5 w-5 text-amber-600 dark:text-amber-400" />}
                </div>
                <div className="min-w-0 flex-1">
                  <h4 className="truncate text-sm font-semibold">{cert.name}</h4>
                  <p className="text-xs text-muted-foreground">{cert.status === "Active" ? `Valid until ${cert.expires}` : "Submitted for validation"}</p>
                </div>
                <Badge variant={cert.status === "Active" ? "default" : "secondary"} className="shrink-0">{cert.status === "Active" ? "Active" : "In progress"}</Badge>
              </div>
            ))}

            <div className="mt-auto rounded-lg bg-emerald-500/10 p-4">
              <div className="flex items-center gap-2">
                <CheckCircle className="h-5 w-5 text-emerald-600 dark:text-emerald-400" />
                <span className="text-sm font-medium">Reduction target: {passport.emissionReductionTarget}% by 2030</span>
              </div>
              <p className="mt-1 text-xs text-muted-foreground">
                {passport.shortfall > 0
                  ? `Buying ${passport.shortfall.toLocaleString()} more credits would fully offset the last 12 months of verified emissions.`
                  : "Your credits fully offset the last 12 months of verified emissions."}
              </p>
              {passport.shortfall > 0 && (
                <Button asChild size="sm" variant="outline" className="mt-3">
                  <Link href="/trading">Buy credits</Link>
                </Button>
              )}
            </div>
          </CardContent>
        </Card>
      </div>
    </motion.div>
  )
}
